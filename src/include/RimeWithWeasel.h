struct CaseInsensitiveCompare {
  bool operator()(const std::string& str1, const std::string& str2) const {
    return std::lexicographical_compare(
        str1.begin(), str1.end(), str2.begin(), str2.end(),
        [](unsigned char a, unsigned char b) {
          return std::tolower(a) < std::tolower(b);
        });
  }
};

typedef std::map<std::string, bool> AppOptions;
typedef std::map<std::string, AppOptions, CaseInsensitiveCompare>
    AppOptionsByAppName;

struct SessionStatus {
  SessionStatus()
      : style(weasel::UIStyle()),
        mode_tip_ascii_initialized(false),
        mode_tip_last_ascii_mode(false),
        mode_tip_requested(false),
        suppress_mode_tip_once(false),
        __synced(false),
        session_id(0) {
    // RIME_STRUCT here would declare a local variable shadowing the member.
    status = {};
    status.data_size = sizeof(RimeStatus) - sizeof(status.data_size);
  }
  weasel::UIStyle style;
  RimeStatus status;
  // CN/EN notification history belongs to an individual TSF session.  The UI
  // object is shared by applications, so its global status cannot safely tell
  // whether this session actually changed modes.
  bool mode_tip_ascii_initialized;
  bool mode_tip_last_ascii_mode;
  // Set only by a direct ascii_mode request from the language bar.  It makes
  // that deliberate toggle visible even when Rime coalesces its notifier.
  bool mode_tip_requested;
  // A physical keypad digit is ordinary text, never a language-mode action.
  // Suppress an asynchronously coalesced ascii_mode notifier for its refresh.
  bool suppress_mode_tip_once;
  bool __synced;
  RimeSessionId session_id;
};
typedef std::map<DWORD, SessionStatus> SessionStatusMap;
